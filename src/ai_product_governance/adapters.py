"""Generate tool-specific integrations from the canonical skill.

`aipg build` renders everything under integrations/ from skills/ai-product-governance;
`aipg build --check` fails when the committed files have drifted from the source. The
skill itself needs no adapter for tools that implement the open Agent Skills standard;
the targets here cover the rest:

  prompt-pack      Custom GPTs, ChatGPT/Claude Projects, Gemini Gems, Microsoft 365
                   Copilot agents, or any LLM via a system prompt plus knowledge files
  github-copilot   Copilot prompt files (slash commands) that drive the skill
  agents-md        An AGENTS.md section for agents that read AGENTS.md but not skills
  mcp              Ready-to-paste MCP client configurations
"""

from __future__ import annotations

import json
from pathlib import Path

from ai_product_governance.skill import SKILL_NAME, Skill, load_skill
from ai_product_governance.workflows import GATES, WORKFLOWS

OUTPUT_DIR = "integrations"
REPOSITORY = "https://github.com/joydeep195/ai-product-governance"
MCP_COMMAND = "uvx"
MCP_ARGS = ["--from", f"git+{REPOSITORY}", "aipg", "serve"]
PROMPT_PACK_CHAR_LIMIT = 8000  # Custom GPT and Copilot Studio instruction limits
GENERATED_NOTE = "<!-- Generated by `aipg build` from skills/ai-product-governance. Do not edit by hand. -->"


def build_outputs(repo: Path) -> dict[str, str]:
    """Return every generated file as {posix path relative to the repo: content}."""
    skill = load_skill(repo / "skills" / SKILL_NAME)
    outputs: dict[str, str] = {}
    outputs.update(_prompt_pack(skill))
    outputs.update(_copilot(skill))
    outputs.update(_agents_md())
    outputs.update(_mcp_clients())
    outputs[f"{OUTPUT_DIR}/README.md"] = _index()
    return dict(sorted(outputs.items()))


def write_outputs(repo: Path, outputs: dict[str, str]) -> list[str]:
    """Write generated files, delete stale ones, and return the paths that changed."""
    changed = []
    for relative, content in outputs.items():
        path = repo / relative
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            path.parent.mkdir(parents=True, exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(content)
            changed.append(relative)
    for stale in _stale_files(repo, outputs):
        (repo / stale).unlink()
        changed.append(f"{stale} (deleted)")
    return changed


def check_outputs(repo: Path, outputs: dict[str, str]) -> list[str]:
    """Return a description of every drift between the committed files and the source."""
    problems = []
    for relative, content in outputs.items():
        path = repo / relative
        if not path.is_file():
            problems.append(f"missing: {relative}")
        elif path.read_text(encoding="utf-8") != content:
            problems.append(f"out of date: {relative}")
    problems.extend(f"stale: {stale}" for stale in _stale_files(repo, outputs))
    return problems


def _stale_files(repo: Path, outputs: dict[str, str]) -> list[str]:
    root = repo / OUTPUT_DIR
    if not root.is_dir():
        return []
    existing = {p.relative_to(repo).as_posix() for p in root.rglob("*") if p.is_file()}
    return sorted(existing - set(outputs))


# --------------------------------------------------------------------------- prompt pack


def prompt_pack_instructions(skill: Skill) -> str:
    gate_rows = [
        f"| {gate.id} {gate.title} | {gate.question} | `{gate.reference}.md` | {_title(gate.template)} |"
        for gate in GATES
    ]
    parts = [
        "# AI Product Governance",
        "",
        skill.section("role"),
        "",
        "## Operating rules",
        "",
        skill.section("rules"),
        "",
        "## How to work",
        "",
        "Every AI feature passes six gates. Find the gate the request is about, read the matching knowledge "
        "file, and produce that gate's artifact from the matching section of `templates.md`.",
        "",
        "| Gate | Question | Knowledge file | Artifact |",
        "|---|---|---|---|",
        *gate_rows,
        "",
        "Approach and model choice: `approach-and-model-selection.md` (model decision record). "
        "Definitions: `glossary.md`.",
        "",
        '- Vague "add AI" requests: run Gate 0 before writing any spec.',
        '- "Write an AI PRD": use the AI PRD template and read the Gate 0, 2 and 3 files.',
        '- "Can we launch?": check each gate\'s exit criteria and decide Go, Go with conditions (an owner and a '
        "date for each) or No-go (with the shortest path to Go).",
        "- Ambiguous request: ask at most three targeted questions, or draft now and record the gaps in the "
        "Assumptions Ledger.",
        "",
        "Paths inside the knowledge files use the original skill layout: `references/<name>.md` is `<name>.md`, "
        "`assets/templates/<name>.md` is a section of `templates.md`, and `scripts/<name>.py` is `<name>.py`.",
        "",
        "## Policy and calculations",
        "",
        "Tiers, controls, approvers and eval minimums come from `default-policy.json`, unless the user supplies "
        "their organisation's policy file, which then takes precedence. Name the policy and version in every "
        "artifact.",
        "",
        "If you can run Python (for example with a code interpreter), use "
        "`python risk_tier.py --answers-json '<json>' --format md` and "
        "`python unit_economics.py --input-json '<json>' --format md`. Otherwise apply the formulas in the "
        "Gate 1 and Gate 3 files and show your working.",
        "",
        "## Output standards",
        "",
        skill.section("output"),
        "",
        "## Scope",
        "",
        skill.section("scope"),
        "",
    ]
    return "\n".join(parts)


def _prompt_pack(skill: Skill) -> dict[str, str]:
    base = f"{OUTPUT_DIR}/prompt-pack"
    files: dict[str, str] = {f"{base}/instructions.md": prompt_pack_instructions(skill)}
    for name in skill.reference_names:
        files[f"{base}/knowledge/{name}.md"] = skill.read_reference(name)
    templates = ["# Artifact templates", "", "Each section below is one template. Copy it and fill it in.", ""]
    for name in skill.template_names:
        templates += [f"<!-- template: {name} -->", "", skill.read_template(name).strip(), "", "---", ""]
    files[f"{base}/knowledge/templates.md"] = "\n".join(templates)
    files[f"{base}/knowledge/default-policy.json"] = skill.default_policy_path.read_text(encoding="utf-8")
    for script in ("risk_tier", "unit_economics"):
        files[f"{base}/knowledge/{script}.py"] = (skill.scripts_dir / f"{script}.py").read_text(encoding="utf-8")
    files[f"{base}/README.md"] = _prompt_pack_readme(len(files) - 1)
    return files


def _prompt_pack_readme(knowledge_count: int) -> str:
    return f"""{GENERATED_NOTE}

# Prompt pack: ChatGPT, Gemini, Microsoft 365 Copilot, Claude Projects or any LLM

Use this when your AI tool cannot load an Agent Skill directly: custom GPTs on ChatGPT plans without
Skills, ChatGPT or Claude Projects, Gemini Gems, Microsoft 365 Copilot agents built in Copilot Studio, or
any model called through an API.

| File | Use it as |
|---|---|
| `instructions.md` | The assistant's instructions or system prompt (under {PROMPT_PACK_CHAR_LIMIT:,} characters) |
| `knowledge/` | Knowledge files to upload ({knowledge_count} files) |

## Set-up by tool

| Tool | Steps |
|---|---|
| ChatGPT custom GPT | Create a GPT → paste `instructions.md` into **Instructions** → upload every file in `knowledge/` → enable **Code Interpreter** so it can run the calculators |
| ChatGPT Project | Paste `instructions.md` into the project instructions → add the `knowledge/` files |
| ChatGPT Business, Enterprise or Edu with Skills | Prefer the skill itself: upload the skill zip from the latest release |
| Claude Project | Paste `instructions.md` into the project instructions → add the `knowledge/` files (or upload the skill zip in Claude's Skills settings) |
| Gemini Gem | Paste `instructions.md` into the Gem instructions → add the `knowledge/` files |
| Microsoft 365 Copilot (Copilot Studio) | Paste `instructions.md` into the agent instructions → add the `knowledge/` files as knowledge sources |
| Any API | Send `instructions.md` as the system prompt; retrieve or attach the relevant knowledge file per request |

Python scripts run only where the tool offers code execution. Without it, the assistant applies the
documented formulas and shows its working.
"""


# --------------------------------------------------------------------------- GitHub Copilot


def _copilot(skill: Skill) -> dict[str, str]:
    base = f"{OUTPUT_DIR}/github-copilot"
    files: dict[str, str] = {}
    for flow in WORKFLOWS:
        placeholder = "${input:" + flow.argument + ":" + flow.argument_hint + "}"
        reads = ", ".join(f"`references/{name}.md`" for name in flow.references)
        files[f"{base}/.github/prompts/{flow.id}.prompt.md"] = "\n".join(
            [
                "---",
                f"name: {flow.id}",
                f"description: {_yaml_string(flow.description)}",
                f"argument-hint: {_yaml_string(flow.argument_hint)}",
                "agent: agent",
                "---",
                "",
                f"Use the **{SKILL_NAME}** Agent Skill (in `.github/skills/` or `.agents/skills/`). "
                "Read its `SKILL.md` first and follow its operating rules.",
                "",
                flow.render_task(placeholder),
                "",
                f"1. Read only these playbooks from the skill: {reads}.",
                f"2. Use the template `assets/templates/{flow.template}.md` and keep every section.",
                "3. Run the skill's `scripts/risk_tier.py` and `scripts/unit_economics.py` for risk tiers and costs; "
                "never estimate them by hand.",
                "4. If `.ai-governance/policy.json` exists in this repository, it overrides the default policy.",
                f"5. Save the result as `docs/ai-governance/<feature>-{flow.template}.md` unless asked otherwise.",
                "",
            ]
        )
    rows = "\n".join(f"| `/{flow.id}` | {flow.description} |" for flow in WORKFLOWS)
    files[f"{base}/README.md"] = f"""{GENERATED_NOTE}

# GitHub Copilot

Copilot (VS Code, Copilot CLI and the Copilot cloud agent) supports the open Agent Skills standard, so the
skill works as-is. These prompt files add one slash command per governance workflow.

## Install

1. Copy `skills/{SKILL_NAME}/` into your repository at `.github/skills/{SKILL_NAME}/`
   (or `.agents/skills/`), or install it with `npx skills add joydeep195/ai-product-governance`.
2. Copy `.github/prompts/` from this folder into your repository's `.github/prompts/`.
3. In Copilot Chat, type `/` and pick a command.

| Command | What it does |
|---|---|
{rows}

For the deterministic tools without running scripts, also connect the MCP server (see `../mcp/`).
"""
    return files


# --------------------------------------------------------------------------- AGENTS.md


def _agents_md() -> dict[str, str]:
    base = f"{OUTPUT_DIR}/agents-md"
    section = f"""## AI product governance

This repository vendors the `{SKILL_NAME}` Agent Skill at `.agents/skills/{SKILL_NAME}/`.

When a task involves planning, specifying, evaluating, approving, launching or troubleshooting an AI or
LLM feature:

1. Read `.agents/skills/{SKILL_NAME}/SKILL.md` and follow its operating rules and gate router.
2. Load only the playbook in `references/` for the gate the task concerns.
3. Use the templates in `assets/templates/` and save artifacts under `docs/ai-governance/`.
4. Compute risk tiers and costs with `python .agents/skills/{SKILL_NAME}/scripts/risk_tier.py` and
   `scripts/unit_economics.py`; never estimate them by hand.
5. If `.ai-governance/policy.json` exists, it overrides the bundled default policy.
"""
    readme = f"""{GENERATED_NOTE}

# AGENTS.md

For coding agents that read `AGENTS.md` but do not load Agent Skills natively. Vendor the skill at
`.agents/skills/{SKILL_NAME}/` and paste the section from `AGENTS.md` in this folder into your
repository's `AGENTS.md`.
"""
    return {f"{base}/AGENTS.md": section, f"{base}/README.md": readme}


# --------------------------------------------------------------------------- MCP clients


def _mcp_clients() -> dict[str, str]:
    base = f"{OUTPUT_DIR}/mcp"
    stdio = {"command": MCP_COMMAND, "args": MCP_ARGS}
    files = {
        f"{base}/claude-desktop.json": _json({"mcpServers": {SKILL_NAME: stdio}}),
        f"{base}/cursor.mcp.json": _json({"mcpServers": {SKILL_NAME: stdio}}),
        f"{base}/gemini-cli.settings.json": _json({"mcpServers": {SKILL_NAME: stdio}}),
        f"{base}/vscode.mcp.json": _json({"servers": {SKILL_NAME: {"type": "stdio", **stdio}}}),
        f"{base}/codex.config.toml": "\n".join(
            [
                f'[mcp_servers."{SKILL_NAME}"]',
                f'command = "{MCP_COMMAND}"',
                "args = [" + ", ".join(f'"{arg}"' for arg in MCP_ARGS) + "]",
                "",
            ]
        ),
    }
    command = " ".join([MCP_COMMAND, *MCP_ARGS])
    files[f"{base}/README.md"] = f"""{GENERATED_NOTE}

# MCP server

The MCP server gives any MCP-capable client the governance playbooks, templates, the effective policy, one
prompt per workflow and two deterministic tools (`classify_risk_tier`, `calculate_unit_economics`).

Run it locally with [uv](https://docs.astral.sh/uv/):

```bash
{command}
```

| Client | File in this folder | Where it goes |
|---|---|---|
| Claude Desktop | `claude-desktop.json` | Merge into `claude_desktop_config.json` |
| VS Code / GitHub Copilot | `vscode.mcp.json` | `.vscode/mcp.json` in your workspace |
| Cursor | `cursor.mcp.json` | `.cursor/mcp.json` |
| Gemini CLI | `gemini-cli.settings.json` | Merge into `.gemini/settings.json` |
| OpenAI Codex | `codex.config.toml` | Merge into `~/.codex/config.toml` |

## Enforce your organisation's policy

Set `AIPG_POLICY` to your policy file in the server's environment (or pass `--policy`). The policy is fixed
at start-up and cannot be changed through a tool call, so every assistant connected to the server applies
the same rules.

## Remote deployment (ChatGPT connectors and shared use)

Clients such as ChatGPT connect to remote MCP servers over HTTPS. Run the server with the Streamable HTTP
transport behind your organisation's gateway, which must terminate TLS and authenticate users:

```bash
aipg serve --transport streamable-http --host 0.0.0.0 --port 8000 --policy /etc/aipg/policy.json
```

Then register the HTTPS URL as a connector where your plan and workspace administrator allow it.
"""
    return files


# --------------------------------------------------------------------------- index


def _index() -> str:
    return f"""{GENERATED_NOTE}

# Integrations

The canonical skill in `skills/{SKILL_NAME}/` follows the open [Agent Skills](https://agentskills.io)
standard and works unchanged in Claude Code and the Claude apps, ChatGPT (plans with Skills), OpenAI Codex,
GitHub Copilot, Cursor, Gemini CLI and other compatible tools. The folders here cover everything else.

| Folder | For |
|---|---|
| [`prompt-pack/`](prompt-pack/) | Custom GPTs, ChatGPT and Claude Projects, Gemini Gems, Microsoft 365 Copilot agents, any LLM API |
| [`github-copilot/`](github-copilot/) | Copilot slash commands for each governance workflow |
| [`agents-md/`](agents-md/) | Agents that read `AGENTS.md` but not skills |
| [`mcp/`](mcp/) | MCP client configurations (Claude Desktop, VS Code, Cursor, Gemini CLI, Codex, ChatGPT connectors) |

Everything in this folder is generated by `aipg build`; CI fails if it drifts from the skill.
"""


# --------------------------------------------------------------------------- helpers


def _title(template: str) -> str:
    return template.replace("-", " ").capitalize().replace("Ai prd", "AI PRD")


def _yaml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _json(data: object) -> str:
    return json.dumps(data, indent=2) + "\n"
